@traceable(name="Bouncer_Math_Validator")
def bouncer_node(state: AgentState) -> AgentState:
    """
    Node 1.7: The Bouncer - Mathematically verifies stamp duty paid.
    """
    print(f"\n⚖️ [BOUNCER] Verifying stamp duty calculations")
    state['current_node'] = 'bouncer'
    state['timestamps']['bouncer_start'] = datetime.now().isoformat()
    state['bouncer_passed'] = False

    def _finish():
        state['timestamps']['bouncer_end'] = datetime.now().isoformat()
        return state

    # Extract required values
    rent = _extract_numeric(state.get('rent_amount'))
    duration_str = state.get('agreement_duration', '')
    # Extract months from "11 months" or "1 year"
    months = 0
    if duration_str:
        # Extract all numeric tokens and their associated units
        # Matches "1.5 years", "6 months", "1yr", etc.
        duration_tokens = re.findall(r'(\d+(?:\.\d+)?)\s*([a-zA-Z]*)', duration_str.lower())
        if duration_tokens:
            total_months = 0.0
            for val_str, unit in duration_tokens:
                val = float(val_str)
                if 'year' in unit or 'yr' in unit:
                    total_months += val * 12
                else:
                    # Assume months if unit is 'month', 'mo', or unspecified
                    total_months += val
            months = int(round(total_months))
        else:
            # Fallback: just extract any number
            tokens = re.findall(r'(\d+(?:\.\d+)?)', duration_str)
            if tokens:
                val = float(tokens[0])
                months = int(round(val * 12)) if any(u in duration_str.lower() for u in ['year', 'yr']) else int(round(val))

    paid = _extract_numeric(state.get('stamp_duty_paid'))

    if rent is None or months == 0 or paid is None:
        error_msg = f"Bouncer Failed: Missing mathematical inputs (Rent: {rent}, Duration: {months}, Paid: {paid})"
        print(f"❌ [BOUNCER] {error_msg}")
        state['errors'].append(error_msg)
        state['bouncer_feedback'] = error_msg
        return _finish()

    # Calculation: Expected = (Rent * Months) * 0.003
    expected = (rent * months) * 0.003

    # Tolerance: ±50 units (rounding)
    if abs(paid - expected) <= 50:
        state['bouncer_passed'] = True
        print(f"✅ [BOUNCER] Stamp duty verified: Found ₹{paid}, Expected ₹{expected:.2f}")
        _record_activity(
            source="agent", staff_kind="agent", staff_short_name="bouncer",
            capability_code="case.validate",
            summary=f"Stamp duty verified: ₹{paid} paid vs ₹{expected:.2f} expected",
            org_id=state.get('org_id'),
            payload={"expected": expected, "actual": paid},
        )
    else:
        error_msg = f"Bouncer Failed: Expected approx ₹{expected:.2f} (0.3% of {rent} * {months}), but found ₹{paid}"
        print(f"❌ [BOUNCER] {error_msg}")
        state['errors'].append(error_msg)
        state['bouncer_feedback'] = error_msg
        _record_activity(
            source="agent", staff_kind="agent", staff_short_name="bouncer",
            capability_code="case.validate",
            summary=error_msg,
            status="error",
            org_id=state.get('org_id'),
            payload={"expected": expected, "actual": paid},
        )

    return _finish()


DRAFTER_SYSTEM_PROMPT = """You are the Drafter, a Legal Architect AI for AG Associates.
Your role is to create professional rental agreements by combining templates with extracted data.

YOUR TASK:
1. Review the extracted tenant/landlord information
2. Use the provided template content as the base structure
3. Inject the extracted variables into appropriate sections
4. Maintain legal language and formatting
5. Ensure all placeholders are replaced with actual data
6. Add today's date as the agreement execution date
7. Format the output as clean Markdown suitable for PDF conversion

IMPORTANT:
- Preserve all legal clauses and terms from the template
- Only replace variable placeholders (marked as {{VARIABLE}} or similar)
- If any critical information is missing, note it at the end under "PENDING INFORMATION"
- Output the complete agreement document

TEMPLATE STRUCTURE TO FOLLOW:
- Title and Parties section
- Property Description
- Term and Rent details
- Security Deposit clause
- Rights and Obligations
- Signatures section
"""


def drafter_node(state: AgentState) -> AgentState:
    """
    Node 2: Drafter - Find template and generate document
    """
    print(f"\n📝 [DRAFTER] Starting document drafting")
    state['current_node'] = 'drafter'
    state['timestamps']['drafter_start'] = datetime.now().isoformat()
    state['revision_count'] = state.get('revision_count', 0) + 1
    
    try:
        # Check if we have extracted data
        if not state.get('extracted_json'):
            raise ValueError("No extracted data available from Aisha")
        
        # Build search query from extracted data
        search_query = f"Maharashtra rent agreement {state.get('property_address', '')}"
        
        # Perform similarity search to find best template
        templates = similarity_search(search_query, limit=3)
        
        if not templates:
            # Fallback: get any Maharashtra rent agreement template
            conn = get_db_connection()
            try:
                cur = conn.cursor()
                try:
                    cur.execute("""
                        SELECT id, title, content, language
                        FROM legal_templates
                        WHERE template_type = 'rent_agreement'
                        AND jurisdiction = 'Maharashtra'
                        LIMIT 1
                    """)
                    fallback_templates = cur.fetchall()
                finally:
                    cur.close()
            finally:
                conn.close()

            if fallback_templates:
                templates = [dict(t) for t in fallback_templates]
            else:
                raise ValueError("No suitable templates found in database")
        
        # Select best template
        best_template = templates[0]
        state['template_id'] = best_template['id']
        template_content = best_template['content']
        state['template_content'] = template_content
        
        print(f"📄 [DRAFTER] Selected template: {best_template['title']} (ID: {best_template['id']})")
        
        # Initialize LLM
        llm = ChatOpenAI(
            model=LLM_MODEL_NAME,
            openai_api_base=LLM_BASE_URL,
            openai_api_key=os.environ.get("LLM_API_KEY", "not-needed"),
            temperature=0.3
        )
        
        # Create prompt
        prompt = ChatPromptTemplate.from_messages([
            ("system", DRAFTER_SYSTEM_PROMPT),
            ("human", """
Extracted Data:
{extracted_data}

Template Content:
{template_content}

Generate the complete rental agreement document:
""")
        ])
        
        chain = prompt | llm
        
        # Prepare extracted data as string
        extracted_str = json.dumps(state['extracted_json'], indent=2, ensure_ascii=False)
        
        # Generate the document
        result = invoke_llm_with_retry(chain, {
            "extracted_data": extracted_str,
            "template_content": template_content
        })
        
        state['drafted_document'] = result.content
        
        # Convert to PDF using ReportLab
        from pdf_generator import convert_to_pdf
        
        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
        pdf_filename = f"agreement_{state['sender']}_{timestamp}"
        
        # Ensure output directory exists
        import os
        from config import OUTPUT_DIR
        os.makedirs(OUTPUT_DIR, exist_ok=True)
        
        # Save markdown version
        md_path = f"{OUTPUT_DIR}/{pdf_filename}.md"
        with open(md_path, 'w', encoding='utf-8') as f:
            f.write(result.content)
        
        # Generate PDF
        try:
            pdf_path = convert_to_pdf(result.content, f"{state['sender']}_{timestamp}")
            state['pdf_path'] = pdf_path
            print(f"✅ [DRAFTER] Document drafted and saved:")
            print(f"   Markdown: {md_path}")
            print(f"   PDF: {pdf_path}")
        except Exception as pdf_error:
            print(f"⚠️ [DRAFTER] PDF generation failed: {str(pdf_error)}")
            print(f"   Markdown saved: {md_path}")
            state['pdf_path'] = md_path  # Fallback to markdown path

        _record_activity(
            source="agent", staff_kind="agent", staff_short_name="drafter",
            capability_code="case.draft",
            summary=f"Drafted document (revision {state.get('revision_count')})",
            payload={"template_id": state.get("template_id"), "pdf_path": state.get("pdf_path")},
            org_id=state.get('org_id'),
        )


        # Success — don't clear state['errors']; prior nodes may have added entries.
        
    except Exception as e:
        error_msg = f"Drafter failed: {str(e)}"
        print(f"❌ [DRAFTER] {error_msg}")
        state['errors'].append(error_msg)
        state['drafted_document'] = None
    
    state['timestamps']['drafter_end'] = datetime.now().isoformat()
    return state


