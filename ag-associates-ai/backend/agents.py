class AgentState(TypedDict):
    """
    State schema for the agent workflow
    Tracks all variables through the pipeline
    """
    # Input from user
    raw_input: str
    sender: str
    org_id: Optional[str]

    # Extracted by Aisha
    tenant_name: Optional[str]
    landlord_name: Optional[str]
    rent_amount: Optional[str]
    property_address: Optional[str]
    agreement_start_date: Optional[str]
    agreement_duration: Optional[str]
    security_deposit: Optional[str]
    stamp_duty_paid: Optional[str]
    extracted_json: Optional[Dict[str, Any]]
    
    # Generated by Drafter
    template_id: Optional[int]
    template_content: Optional[str]
    drafted_document: Optional[str]
    pdf_path: Optional[str]
    
    # Guardrail result
    guardrail_passed: bool
    bouncer_passed: bool
    bouncer_feedback: Optional[str]

    # Audit results
    audit_passed: bool
    audit_feedback: Optional[str]
    revision_count: int
    
    # Metadata
    current_node: str
    errors: List[str]
    timestamps: Dict[str, str]


def get_db_connection():
    """Create database connection with pgvector support"""
    conn = psycopg2.connect(
        get_database_url(),
        cursor_factory=RealDictCursor
    )
    register_vector(conn)
    return conn


# Lazy-loaded SentenceTransformer — initialised on first call to avoid
# import-time overhead and to keep startup fast when the backend is used
# without any RAG queries (e.g. health checks).
_embedding_model = None


def _get_embedding_model():
    global _embedding_model
    if _embedding_model is None:
        from sentence_transformers import SentenceTransformer
        _embedding_model = SentenceTransformer(EMBEDDING_MODEL_NAME)
    return _embedding_model


def generate_embedding(text: str) -> List[float]:
    """
    Generate a real vector embedding for the given text using SentenceTransformer.
    """
    model = _get_embedding_model()
    embedding = model.encode(text)
    return embedding.tolist()


def similarity_search(query: str, limit: int = 3) -> List[Dict[str, Any]]:
    """
    Perform similarity search in PostgreSQL to find relevant templates
    """
    # Generate embedding for the query
    query_embedding = generate_embedding(query)

    conn = get_db_connection()
    try:
        cur = conn.cursor()
        try:
            # Perform vector similarity search
            cur.execute("""
                SELECT id, title, content, language, jurisdiction,
                       1 - (embedding <=> %s::vector) as similarity
                FROM legal_templates
                ORDER BY embedding <=> %s::vector
                LIMIT %s
            """, (query_embedding, query_embedding, limit))

            results = cur.fetchall()
        finally:
            cur.close()
    finally:
        conn.close()

    return [dict(row) for row in results]


